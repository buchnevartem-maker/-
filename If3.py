# --- Заголовок ------------------------------------
title = "ЗАБРОШЕННАЯ ШАХТА"
frame = "=" * (len(title) + 6)
print(frame)
print(f"   {title}   ")
print(frame)
print()
# --- Знакомство с героем --------------------------
print("Как зовут героя?")
hero_name = input()
print(f"Добро пожаловать, {hero_name}!")
print("Ты стоишь у входа в заброшенную шахту. Оттуда тянет могильным холодом и угольной пылью.")
print()
# --- Настройка героя -------------------------------
print("Настройка героя.")
print("Здоровье, сила, ловкость, удача — по одному числу в строке:")
health = int(input())
strength = int(input())
agility = int(input())
luck = int(input())
print()
# --- Расчёт урона ----------------------------------
base_attack = 10
damage = base_attack + strength * 1.5
crit_damage = damage * 2
stamina = (health // 10) + luck
# --- Формуляр героя --------------------------------
print("Характеристики героя:")
print(f"Здоровье: {health}")
print(f"Сила:     {strength}")
print(f"Ловкость: {agility}")
print(f"Удача:    {luck}")
print()
print(f"Урон героя:       {damage:.1f}")
print(f"Критический урон: {crit_damage:.1f}")
print(f"Запас сил:        {stamina}")
print()
# --- Меню действий ---------------------------------
print("Что делаешь?")
print("1 - осмотреться")
print("2 - идти вперёд")
print("3 - отдохнуть")
print("4 - постучать по стене")
print("5 - зажечь фонарь")
# --- Выбор действия --------------------------------
choice = input()
match choice:
    case "1":
        print("Вы осмотрелись. Стены покрыты каменистой пылью, вдали виден тёмный проход.")
    case "2":
        stamina = stamina - 2
        print("Вы осторожно идёте вперёд. Под ногами хрустит мелкая угольная крошка.")
    case "3":
        stamina = stamina + 3
        print("Вы переводите дух и немного отдыхаете в тишине.")
    case "4":
        print("Вы постучали по стене. Звук глухой — за камнем сплошная порода.")
    case "5":
        stamina = stamina - 1
        print("Вы зажгли фонарь. Тьма немного отступила, стало уютнее.")
    case _:
        print("Такого действия нет.")
# --- Строка состояния ------------------------------
print()
print(f"Здоровье: {health}  Запас сил: {stamina}")
# --- Прощание --------------------------------------
print()
print(frame)
print(f"Удачи во тьме, {hero_name}! Она тебе понадобится.")
print(frame)
