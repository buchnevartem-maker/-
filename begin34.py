# Begin34. Цена 1 кг шоколадных конфет и ирисок, отношение цен.
x = float(input())
price_chocolate = float(input())
y = float(input())
price_toffee = float(input())
chocolate_per_kg = price_chocolate / x
toffee_per_kg = price_toffee / y
ratio = chocolate_per_kg / toffee_per_kg
print(chocolate_per_kg)
print(toffee_per_kg)
print(ratio)
